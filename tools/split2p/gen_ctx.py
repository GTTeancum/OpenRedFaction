"""Generate src/diagnostic/scene_player_context.inc from the per-player classification."""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
import sys
sys.path.insert(0, HERE)
from classify import inc
names = sorted(n for n, s, t in inc)
L = []
L.append('/* Two-player split screen, stage 1 (docs/SPLIT-SCREEN-2P.md): every')
L.append(' * per-player scene global, exchanged as a block so the existing one-player')
L.append(' * code runs for either human. Generated by tools/split2p/gen_ctx.py from')
L.append(' * the scene object\'s symbol table and name rules; shared world state is')
L.append(' * never listed. Function-local statics are not reachable here (see the')
L.append(' * design doc). Edit the rules and regenerate rather than by hand. */')
L.append('#define SCENE_PLAYER_STATE(X) ' + chr(92))
for i, n in enumerate(names):
    L.append('    X(%s)%s' % (n, ' ' + chr(92) if i + 1 < len(names) else ''))
L.append('#define SCENE_PLAYER_SIZE(name) +sizeof(name)')
L.append('enum {SCENE_PLAYER_STORE_BYTES=0 SCENE_PLAYER_STATE(SCENE_PLAYER_SIZE)};')
L.append('#undef SCENE_PLAYER_SIZE')
L.append('#define SCENE_PLAYER_REGION(name) {&name,sizeof(name)},')
L.append('static const struct {void *address;uint32_t bytes;} scene_player_regions[]={SCENE_PLAYER_STATE(SCENE_PLAYER_REGION)};')
L.append('#undef SCENE_PLAYER_REGION')
L.append('/* Parked state of the human not currently live (one block: two players). */')
L.append('static uint8_t scene_player_store[SCENE_PLAYER_STORE_BYTES];')
L.append('uint32_t rf_scene_player_context[4]; /* harness: live player, exchanges, store bytes, self-test */')
L.append('/* Exchange the live player globals with the parked block. */')
L.append('static void scene_player_exchange(void)')
L.append('{')
L.append('    static uint8_t temporary[4096];uint8_t *store=scene_player_store;uint32_t i,j,n;')
L.append('    for(i=0;i<sizeof(scene_player_regions)/sizeof(scene_player_regions[0]);i++){')
L.append('        uint8_t *live=(uint8_t *)scene_player_regions[i].address;')
L.append('        for(j=0;j<scene_player_regions[i].bytes;j+=n){')
L.append('            n=scene_player_regions[i].bytes-j;if(n>sizeof(temporary))n=sizeof(temporary);')
L.append('            memcpy(temporary,live+j,n);memcpy(live+j,store+j,n);memcpy(store+j,temporary,n);')
L.append('        }')
L.append('        store+=scene_player_regions[i].bytes;')
L.append('    }')
L.append('    rf_scene_player_context[0]^=1u;++rf_scene_player_context[1];rf_scene_player_context[2]=SCENE_PLAYER_STORE_BYTES;')
L.append('}')
L.append('/* Make player slot (0 or 1) live. */')
L.append('__attribute__((unused)) static void scene_player_select(uint32_t slot)')
L.append('{if((slot&1u)!=rf_scene_player_context[0])scene_player_exchange();}')
L.append('/* Park a copy of the live player as the other slot (match start). */')
L.append('__attribute__((unused)) static void scene_player_clone(void)')
L.append('{')
L.append('    uint8_t *store=scene_player_store;uint32_t i;')
L.append('    for(i=0;i<sizeof(scene_player_regions)/sizeof(scene_player_regions[0]);i++){')
L.append('        memcpy(store,scene_player_regions[i].address,scene_player_regions[i].bytes);store+=scene_player_regions[i].bytes;')
L.append('    }')
L.append('}')
L.append('static void scene_player_test_mark(void){++rf_scene_player_context[3];}')
open(os.path.join(HERE, '..', '..', 'src', 'diagnostic', 'scene_player_context.inc'), 'w', newline='\n').write('\n'.join(L) + '\n')
print(len(names), 'names')
