        def dct(name, t):
            rows = []
            for c, r, l in t:
                r = 63 if r == 'eob' else 62 if r == 'esc' else r
                rows.append('{0x%04x,%d,%d,%d}' % (int(c, 2), len(c), r, l))
            print('static const mpeg2_code %s[]={%s};' % (name, ','.join(rows)))
