def check(name, table, slack=0.0):
    codes = [t[0] for t in table]
    assert len(set(codes)) == len(codes), (name, 'duplicate')
    for a in codes:
        for b in codes:
            assert a == b or not b.startswith(a), (name, 'prefix', a, b)
    kraft = sum(2.0 ** -len(c) for c in codes)
    print(f'{name}: {len(codes)} codes, Kraft sum {kraft:.6f}')
    return kraft

